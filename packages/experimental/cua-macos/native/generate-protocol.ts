/** Generate macOS admission artifacts from the shared CUA operation definitions. */
import { readFile, writeFile } from 'node:fs/promises'
import { z } from 'zod'
import { AX_TRAVERSAL_MAX } from '../src/ax-limits.ts'
import { NativeResourceParameters } from '@deepseek-ai/dsh-cua/protocol'
import { nativeProtocol } from '@deepseek-ai/dsh-cua/native-schema'
import { PermissionGuideParameters, PermissionSettingsParameters } from '../src/permission-guide.ts'

/**
 * Render native artifacts; platform actions and lifecycle remain handwritten.
 * @returns Native JSON Schema and Swift field/enum tables, including private continuations.
 */
export function renderNativeProtocol(): { json: string; swift: string } {
  const traversal = {
    maxElements: z.number().int().min(1).max(AX_TRAVERSAL_MAX.maxElements),
    maxDepth: z.number().int().min(1).max(AX_TRAVERSAL_MAX.maxDepth),
  }
  const systemPointer = { useSystemPointer: z.boolean().optional() }
  const { fields, enums, json } = nativeProtocol({
    getState: NativeResourceParameters.getState.extend(traversal),
    paste: NativeResourceParameters.paste.extend(traversal),
    sendKeyEvent: z.object({ runId: z.string().min(1) }),
    mouseMove: z.object(systemPointer),
    drag: NativeResourceParameters.drag.extend(systemPointer),
    requestPermission: PermissionGuideParameters, openPermissionSettings: PermissionSettingsParameters,
  }, [z.object({
    method: z.literal('releaseHeldKeys'), params: z.object({ runId: z.string().min(1) }).strict(),
  }).strict()])
  const quoted = (values: Iterable<string>) => [...values].sort().map(value => JSON.stringify(value)).join(', ')
  const swift = [
    '// Generated by native/generate-protocol.ts from @deepseek-ai/dsh-cua/native-schema. Do not edit.',
    'enum NativeProtocol {',
    `    static let elementRange = 1...${AX_TRAVERSAL_MAX.maxElements}`,
    `    static let depthRange = 1...${AX_TRAVERSAL_MAX.maxDepth}`,
    '    static let fields: [String: Set<String>] = [',
    ...[...fields].sort(([a], [b]) => a.localeCompare(b)).map(([method, names]) => `        ${JSON.stringify(method)}: [${quoted(names)}],`),
    '    ]',
    '    static let stringEnums: [String: [String: Set<String>]] = [',
    ...[...enums].sort(([a], [b]) => a.localeCompare(b)).map(([method, properties]) =>
      `        ${JSON.stringify(method)}: [${[...properties].sort(([a], [b]) => a.localeCompare(b))
        .map(([name, values]) => `${JSON.stringify(name)}: [${quoted(values)}]`).join(', ')}],`),
    '    ]',
    '}',
    '',
  ].join('\n')
  return { swift, json }
}

if (import.meta.main) {
  const generated = renderNativeProtocol()
  for (const [file, content] of [
    ['protocol.schema.json', generated.json], ['Sources/CuaNative/NativeProtocol.generated.swift', generated.swift],
  ] as const) {
    const path = new URL(file, import.meta.url)
    if (process.argv.includes('--check')) {
      if (await readFile(path, 'utf8') !== content) throw new Error(`Stale generated CUA protocol: ${file}`)
    } else await writeFile(path, content)
  }
}
